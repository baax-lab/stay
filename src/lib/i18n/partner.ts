export const PARTNER_DICTS: Record<PartnerLang, Dict> = { de, en, es, it, fr };

export function tp(lang: PartnerLang, key: string, vars?: Record<string, string | number>): string {
  let s = PARTNER_DICTS[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function partnerLocale(lang: PartnerLang): string {
  return { de: "de-DE", en: "en-GB", es: "es-ES", it: "it-IT", fr: "fr-FR" }[lang];
}
